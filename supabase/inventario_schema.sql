-- Depois importar os CSVs de artigos e códigos de barras nas tabelas correspondentes.

create extension if not exists pgcrypto;

create table if not exists public.inv_artigos (
  codigo_artigo text primary key,
  descricao text not null,
  iva numeric(5,2),
  preco_custo numeric(12,4),
  ativo boolean not null default true,
  atualizado_em timestamptz not null default now()
);

create table if not exists public.inv_codigos_barras (
  id bigint generated by default as identity primary key,
  codigo_barras text not null,
  codigo_artigo text not null references public.inv_artigos(codigo_artigo) on delete cascade,
  criado_em timestamptz not null default now(),
  constraint inv_codigos_barras_codigo_artigo_un unique (codigo_barras, codigo_artigo)
);
create index if not exists inv_codigos_barras_codigo_idx on public.inv_codigos_barras (codigo_barras);
create index if not exists inv_artigos_descricao_idx on public.inv_artigos using gin (to_tsvector('simple', descricao));

create table if not exists public.inv_perfis (
  user_id uuid primary key references auth.users(id) on delete cascade,
  nome text,
  loja text not null,
  perfil text not null default 'loja' check (perfil in ('loja','central')),
  ativo boolean not null default true
);

create table if not exists public.inv_inventarios (
  id uuid primary key default gen_random_uuid(),
  loja text not null,
  nome text not null default 'Inventário',
  estado text not null default 'aberto' check (estado in ('aberto','fechado')),
  criado_por uuid not null default auth.uid() references auth.users(id),
  criado_em timestamptz not null default now(),
  fechado_em timestamptz
);
create unique index if not exists inv_um_inventario_aberto_por_loja
  on public.inv_inventarios (loja) where estado = 'aberto';

create table if not exists public.inv_contagens (
  id uuid primary key default gen_random_uuid(),
  inventario_id uuid not null references public.inv_inventarios(id) on delete cascade,
  codigo_artigo text not null references public.inv_artigos(codigo_artigo),
  codigo_barras_lido text,
  quantidade numeric(12,3) not null check (quantidade >= 0),
  utilizador_id uuid not null default auth.uid() references auth.users(id),
  dispositivo_id text,
  contado_em timestamptz not null default now()
);
create index if not exists inv_contagens_inventario_artigo_idx on public.inv_contagens (inventario_id, codigo_artigo);
create index if not exists inv_contagens_contado_em_idx on public.inv_contagens (contado_em desc);

create or replace function public.inv_pode_aceder_loja(p_loja text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.inv_perfis p
    where p.user_id = auth.uid() and p.ativo = true
      and (p.perfil = 'central' or p.loja = p_loja)
  );
$$;

alter table public.inv_artigos enable row level security;
alter table public.inv_codigos_barras enable row level security;
alter table public.inv_perfis enable row level security;
alter table public.inv_inventarios enable row level security;
alter table public.inv_contagens enable row level security;

drop policy if exists "artigos leitura autenticada" on public.inv_artigos;
create policy "artigos leitura autenticada" on public.inv_artigos for select to authenticated using (true);
drop policy if exists "codigos leitura autenticada" on public.inv_codigos_barras;
create policy "codigos leitura autenticada" on public.inv_codigos_barras for select to authenticated using (true);
drop policy if exists "perfil proprio leitura" on public.inv_perfis;
create policy "perfil proprio leitura" on public.inv_perfis for select to authenticated using (user_id = auth.uid());
drop policy if exists "inventarios leitura loja" on public.inv_inventarios;
create policy "inventarios leitura loja" on public.inv_inventarios for select to authenticated using (public.inv_pode_aceder_loja(loja));
drop policy if exists "inventarios criar loja" on public.inv_inventarios;
create policy "inventarios criar loja" on public.inv_inventarios for insert to authenticated
with check (public.inv_pode_aceder_loja(loja) and criado_por = auth.uid());
drop policy if exists "inventarios atualizar loja" on public.inv_inventarios;
create policy "inventarios atualizar loja" on public.inv_inventarios for update to authenticated
using (public.inv_pode_aceder_loja(loja)) with check (public.inv_pode_aceder_loja(loja));
drop policy if exists "contagens leitura loja" on public.inv_contagens;
create policy "contagens leitura loja" on public.inv_contagens for select to authenticated using (
  exists (select 1 from public.inv_inventarios i where i.id = inventario_id and public.inv_pode_aceder_loja(i.loja))
);
drop policy if exists "contagens inserir loja" on public.inv_contagens;
create policy "contagens inserir loja" on public.inv_contagens for insert to authenticated with check (
  utilizador_id = auth.uid() and exists (
    select 1 from public.inv_inventarios i where i.id = inventario_id
      and i.estado = 'aberto' and public.inv_pode_aceder_loja(i.loja)
  )
);
drop policy if exists "contagens apagar propria loja" on public.inv_contagens;
create policy "contagens apagar propria loja" on public.inv_contagens for delete to authenticated using (
  utilizador_id = auth.uid() and exists (
    select 1 from public.inv_inventarios i where i.id = inventario_id and public.inv_pode_aceder_loja(i.loja)
  )
);

grant usage on schema public to authenticated;
grant select on public.inv_artigos, public.inv_codigos_barras, public.inv_perfis,
  public.inv_inventarios, public.inv_contagens to authenticated;
grant insert, update on public.inv_inventarios to authenticated;
grant insert, delete on public.inv_contagens to authenticated;
