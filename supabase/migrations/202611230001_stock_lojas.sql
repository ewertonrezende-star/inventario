-- Inventário Coopsintra: stock Primavera separado por artigo e armazém.
-- Executar no SQL Editor do projeto Supabase uacadlvvonvriiqdxdfr.

create table if not exists public.inv_stock_lojas (
  id bigint generated by default as identity primary key,
  codigo_artigo text not null references public.inv_artigos(codigo_artigo) on delete cascade,
  armazem text not null check (armazem in ('AL','AM','CO','MM','LC','SA','CC')),
  stock_atual numeric(14,3) not null default 0,
  atualizado_em timestamptz not null default now(),
  constraint inv_stock_lojas_artigo_armazem_un unique (codigo_artigo, armazem)
);

create index if not exists inv_stock_lojas_armazem_idx
  on public.inv_stock_lojas (armazem);
create index if not exists inv_stock_lojas_artigo_idx
  on public.inv_stock_lojas (codigo_artigo);

alter table public.inv_stock_lojas enable row level security;

drop policy if exists "stock leitura loja" on public.inv_stock_lojas;
create policy "stock leitura loja"
  on public.inv_stock_lojas for select to authenticated
  using (public.inv_pode_aceder_loja(armazem));

drop policy if exists "stock importar central" on public.inv_stock_lojas;
create policy "stock importar central"
  on public.inv_stock_lojas for insert to authenticated
  with check (exists (
    select 1 from public.inv_perfis p
    where p.user_id = auth.uid() and p.ativo = true and p.perfil = 'central'
  ));

drop policy if exists "stock atualizar central" on public.inv_stock_lojas;
create policy "stock atualizar central"
  on public.inv_stock_lojas for update to authenticated
  using (exists (
    select 1 from public.inv_perfis p
    where p.user_id = auth.uid() and p.ativo = true and p.perfil = 'central'
  ))
  with check (exists (
    select 1 from public.inv_perfis p
    where p.user_id = auth.uid() and p.ativo = true and p.perfil = 'central'
  ));

grant usage on schema public to authenticated;
grant select, insert, update on public.inv_stock_lojas to authenticated;
grant usage, select on sequence public.inv_stock_lojas_id_seq to authenticated;
